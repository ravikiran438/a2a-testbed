@pytest.mark.asyncio
async def test_local_manifest_store_round_trip(tmp_path, fake_manifest):
    path = tmp_path / "example.org" / "fake-protocol" / "v1" / "manifest.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        fake_manifest.model_dump_json(by_alias=True, indent=2, exclude_none=True),
        encoding="utf-8",
    )
    store = LocalManifestStore(tmp_path)
    found = await store.fetch(FAKE_URI)
    assert found is not None
    assert found.extension.uri == FAKE_URI


@pytest.mark.asyncio
async def test_local_manifest_store_returns_none_when_missing(tmp_path):
    store = LocalManifestStore(tmp_path)
    assert await store.fetch(FAKE_URI) is None


# --------------------------------------------------------------------------
# Integration: validate against the manifests published on github.io
# for the four reference protocols (ACAP/Phala/NERVE/PACE). This test
# fetches the live manifests over HTTPS — same path any third-party
# validator would take. Skipped when no network is available.
# --------------------------------------------------------------------------


SHIPPED_MANIFEST_URIS = [
    "https://ravikiran438.github.io/agent-consent-protocol/v1",
    "https://ravikiran438.github.io/phala-protocol/v1",
    "https://ravikiran438.github.io/pratyahara-nerve/v1",
    "https://ravikiran438.github.io/sauvidya-pace/v1",
]


@pytest.mark.parametrize("uri", SHIPPED_MANIFEST_URIS)
def test_shipped_manifest_loads_and_validates(uri):
    import httpx
    manifest_url = uri.rstrip("/") + "/manifest.json"
    try:
        resp = httpx.get(manifest_url, timeout=5.0)
    except (httpx.ConnectError, httpx.TimeoutException) as exc:
        pytest.skip(f"network unavailable: {exc}")
    if resp.status_code != 200:
        pytest.skip(f"manifest not yet published at {manifest_url} ({resp.status_code})")
    raw = json.loads(resp.text)
    manifest = ExtensionManifest.model_validate(raw)
    assert manifest.extension.uri == uri
    assert isinstance(manifest.agent_card_payload_schema, dict)
    assert manifest.agent_card_payload_schema.get("type") == "object"
