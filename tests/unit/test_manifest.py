def _store_with(manifest: ExtensionManifest) -> InMemoryManifestStore:
    return InMemoryManifestStore({manifest.extension.uri: manifest})


@pytest.fixture
def fake_manifest() -> ExtensionManifest:
    return generate_manifest(
        extension_uri=FAKE_URI,
        name="Fake Protocol",
        version="1.0.0",
        ref_class=FakeServiceRef,
    )


def _card_declaring(uri: str, payload: dict | None) -> dict:
    entry: dict = {"uri": uri, "description": "Supports fake protocol."}
    if payload is not None:
        entry["params"] = payload
    return {
        "name": "test agent",
        "capabilities": {"extensions": [entry]},
    }


@pytest.mark.asyncio
async def test_validate_declared_ok(fake_manifest):
    card = _card_declaring(
        FAKE_URI,
        {"version": "1.0.0", "endpoint": "https://x/y", "weight_keys": []},
    )
    findings = await validate_agent_card(card, store=_store_with(fake_manifest))
    assert len(findings) == 1
    assert findings[0].kind == FindingKind.DECLARED_OK


@pytest.mark.asyncio
async def test_validate_declared_invalid_missing_required_field(fake_manifest):
    card = _card_declaring(
        FAKE_URI,
        {"version": "1.0.0"},  # missing 'endpoint'
    )
    findings = await validate_agent_card(card, store=_store_with(fake_manifest))
    assert len(findings) == 1
    f = findings[0]
    assert f.kind == FindingKind.DECLARED_INVALID
    assert any("endpoint" in err for err in f.schema_errors)


@pytest.mark.asyncio
async def test_validate_declared_invalid_wrong_type(fake_manifest):
    card = _card_declaring(
        FAKE_URI,
        {"version": "1.0.0", "endpoint": 42, "weight_keys": []},
    )
    findings = await validate_agent_card(card, store=_store_with(fake_manifest))
    assert findings[0].kind == FindingKind.DECLARED_INVALID
    # JSON Schema reports the type mismatch under the offending field.
    assert any("endpoint" in err for err in findings[0].schema_errors)


