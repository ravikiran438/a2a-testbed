"""Tests for the manifest generator + dynamic AgentCard validator.

These exercise the manifest pipeline end to end against real pydantic
models from the four protocol packages, so they double as a smoke test
that the testbed can validate any A2A extension that ships a manifest.
"""

from __future__ import annotations

import json

import pytest
from pydantic import BaseModel, Field

from a2a_testbed.manifest import (
    ExtensionManifest,
    ExtensionMetadata,
    Finding,
    FindingKind,
    InMemoryManifestStore,
    LocalManifestStore,
    generate_manifest,
    manifest_url_for_uri,
    validate_agent_card,
)


# --------------------------------------------------------------------------
# Fixture pydantic model — the kind a third-party protocol author would write
# --------------------------------------------------------------------------


class FakeServiceRef(BaseModel):
    """Stand-in for a real protocol's *Ref class."""

    version: str
    endpoint: str = Field(..., description="HTTPS data plane URL")
    weight_keys: list[str] = Field(default_factory=list)


FAKE_URI = "https://example.org/fake-protocol/v1"


# --------------------------------------------------------------------------
# Generator
# --------------------------------------------------------------------------


def test_manifest_uri_url_convention():
    assert (
        manifest_url_for_uri(FAKE_URI)
        == "https://example.org/fake-protocol/v1/manifest.json"
    )


def test_generator_emits_well_formed_manifest():
    m = generate_manifest(
        extension_uri=FAKE_URI,
        name="Fake Protocol",
        version="1.0.0",
        ref_class=FakeServiceRef,
        description="test",
        publisher="Example Corp",
        invariants=["I-1: foo"],
    )
    assert m.manifest_version == "1.0.0"
    assert m.extension.uri == FAKE_URI
    assert m.extension.name == "Fake Protocol"
    assert m.invariants == ["I-1: foo"]
    # JSON Schema generated by pydantic carries the typed required fields.
    schema = m.agent_card_payload_schema
    assert "version" in schema["required"]
    assert "endpoint" in schema["required"]
    assert "weight_keys" not in schema.get("required", [])


def test_generator_accepts_dotted_path():
    m = generate_manifest(
        extension_uri=FAKE_URI,
        name="Fake",
        version="1.0.0",
        ref_class="tests.unit.test_manifest:FakeServiceRef",
    )
    assert m.extension.uri == FAKE_URI


def test_generator_resolves_wire_artefact_dotted_paths():
    m = generate_manifest(
        extension_uri=FAKE_URI,
        name="Fake",
        version="1.0.0",
        ref_class=FakeServiceRef,
        wire_artefacts=[
            {
                "name": "FakeArtefact",
                "endpoint_field": "endpoint",
                "schema": "tests.unit.test_manifest:FakeServiceRef",
            }
        ],
    )
    assert len(m.wire_artefacts) == 1
    assert m.wire_artefacts[0].json_schema["title"] == "FakeServiceRef"


def test_generator_no_ref_class_uses_opaque_payload_schema():
    """Extensions that augment runtime behavior get a permissive schema."""
    m = generate_manifest(
        extension_uri="https://example.org/runtime-only/v1",
        name="Runtime-Only Extension",
        version="1.0.0",
        # ref_class omitted
    )
    schema = m.agent_card_payload_schema
    assert schema["type"] == "object"
    assert schema["title"] == "OpaquePayload"
    assert schema["additionalProperties"] is True


@pytest.mark.asyncio
async def test_validator_accepts_any_object_against_opaque_schema():
    """OpaquePayload schema must accept arbitrary params (or absent ones)."""
    runtime_uri = "https://example.org/runtime-only/v1"
    runtime_manifest = generate_manifest(
        extension_uri=runtime_uri,
        name="Runtime-Only",
        version="1.0.0",
        # no ref_class -> OpaquePayload
    )
    store = InMemoryManifestStore({runtime_uri: runtime_manifest})

    # An arbitrary payload should validate against OpaquePayload.
    card = _card_declaring(runtime_uri, {"anything": [1, 2, 3], "else": "ok"})
    findings = await validate_agent_card(card, store=store)
    assert findings[0].kind == FindingKind.DECLARED_OK


def test_generator_rejects_non_pydantic_class():
    class NotPydantic:
        pass

    with pytest.raises(TypeError):
        generate_manifest(
            extension_uri=FAKE_URI,
            name="X",
            version="1.0.0",
            ref_class=NotPydantic,  # type: ignore[arg-type]
        )


